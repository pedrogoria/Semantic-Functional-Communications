"""
tests/debug_sod_full_system.py

Full-system debug runner for Send-on-Delta (SoD) under FDMA-style channel budget.

This debug follows the project output convention:

    tests/results/<debug_name>/YYYYMMDD_HHMMSS/

By default:

    tests/results/debug_sod_full_system/YYYYMMDD_HHMMSS/

It saves:
- a copy of the YAML config used, or the generated default config;
- metadata JSON;
- arrays NPZ;
- figures in the configured formats.

Purpose
-------
Visualize and diagnose the SoD branch with the physically correct chain:

    X random
    -> filter_periodic(...)
    -> remove DC
    -> peak-to-peak adjustment
    -> SoD acquisition WITHOUT quantization, to determine event_count
    -> compute M_SoD from channel capacity and event_count
    -> SoD acquisition WITH quantization using M_SoD
    -> received/dequantized SoD event samples
    -> dense SoD reconstruction
    -> sinc_filter(...) reconstruction
    -> MSE and plots

Important budget rule
---------------------
For adaptive/event-driven methods, the number of bins is NOT copied from the
Benchmark Approach. Instead, it is computed from the available channel budget and
the actual number of transmitted objects.

For SoD, if K_s events are generated by sensor s in one period and R_s bits are
available, then:

    K_s * fields_per_event * log2(M_SoD,s) <= R_s

where:

    fields_per_event = 2, if event time + amplitude are transmitted
    fields_per_event = 1, if amplitude-only optimistic mode is used

The feasible M_SoD,s is computed by:

    sfc.core.theory.compute_M_sod_per_sensor(...)

Core usage
----------
This file uses core functions/classes for the actual system operations:

    sfc.core.filters.filter_periodic
    sfc.core.filters.sinc_filter
    sfc.core.acquisition.sod.SoDAcquisitionCore
    sfc.core.system_parameters.build_derived_system_parameters
    sfc.core.mac.fdma.FDMACore
    sfc.core.theory.compute_M_sod_per_sensor

Local debug logic introduced here
---------------------------------
Only lightweight debug utilities are implemented locally:
- YAML loading and output-directory management;
- random source generation;
- DC removal using the same period convention used in the project;
- peak-to-peak scaling;
- plotting and metadata serialization.

No channel-capacity formula is reimplemented here. FDMA budget quantities are
obtained through core modules.

Usage
-----
Python console:

    from tests.debug_sod_full_system import run_debug_sod_full_system

    out = run_debug_sod_full_system(
        config_path="tests/configs/sod_full_system_debug.yaml",
        show_plots=True
    )

or without YAML:

    out = run_debug_sod_full_system(show_plots=True)

Terminal:

    python tests/debug_sod_full_system.py

or:

    python tests/debug_sod_full_system.py --config tests/configs/sod_full_system_debug.yaml --show
"""

