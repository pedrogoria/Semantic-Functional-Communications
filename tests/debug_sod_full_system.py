def figure_formats(cfg: Dict[str, Any]) -> list:
    """
    Resolve figure formats from config.
    """
    formats = cfg.get("output", {}).get("formats", {}).get("figure", None)

    if formats is None:
        formats = cfg.get("output", {}).get("formats", {}).get("plot", ["png", "pdf"])

    return list(formats)


def save_figure(fig, output_dir: str, base_name: str, formats: list) -> Dict[str, str]:
    """
    Save figure in requested formats.

    Figures are not closed here so that show_plots=True can display them at the
    end. The caller closes all figures when interactive display is disabled.
    """
    generated = {}

    for fmt in formats:
        path = os.path.join(output_dir, "{}.{}".format(base_name, fmt))

        if fmt == "png":
            fig.savefig(path, dpi=300, bbox_inches="tight")
        elif fmt == "pdf":
            fig.savefig(path, bbox_inches="tight")
        else:
            raise ValueError("Unsupported figure format: {}".format(fmt))

        generated[fmt] = path

    return generated


