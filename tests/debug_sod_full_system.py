def _generate_random_signal(n_time: int, distribution: str, rng: np.random.Generator) -> np.ndarray:
    """
    Generate random source signal for debug.
    """
    distribution = str(distribution).lower()

    if distribution == "uniform":
        return rng.uniform(-1.0, 1.0, size=n_time)

    if distribution == "gaussian":
        return rng.normal(0.0, 1.0, size=n_time)

    raise ValueError("signal.distribution must be 'uniform' or 'gaussian'.")


def _remove_dc_one_period(x: np.ndarray, Tt: float, tau: float) -> tuple:
    """
    Remove DC using the same discrete-period convention used elsewhere:

        dc = Tt * sum(x) / tau
    """
    x = np.asarray(x, dtype=float)
    dc = float(Tt * np.sum(x) / tau)
    return x - dc, dc


def _adjust_peak_to_peak(x: np.ndarray, peak_to_peak: float) -> tuple:
    """
    Scale signal to requested peak-to-peak value.
    """
    x = np.asarray(x, dtype=float)
    peak_to_peak = float(peak_to_peak)

    if peak_to_peak == 0:
        return np.array(x, copy=True), 1.0

    current_p2p = float(np.max(x) - np.min(x))

    if np.isclose(current_p2p, 0.0):
        return np.array(x, copy=True), 1.0

    scale = peak_to_peak / current_p2p
    return x * scale, scale


def _compute_mse(x_ref: np.ndarray, x_hat: np.ndarray) -> float:
    """
    Compute MSE.
    """
    x_ref = np.asarray(x_ref, dtype=float)
    x_hat = np.asarray(x_hat, dtype=float)

    if x_ref.shape != x_hat.shape:
        raise ValueError(
            "Shape mismatch: x_ref.shape={} and x_hat.shape={}".format(
                x_ref.shape,
                x_hat.shape,
            )
        )

    return float(np.mean((x_ref - x_hat) ** 2))


def _make_json_safe(obj: Any):
    """
    Convert object to JSON-safe representation.
    """
    if isinstance(obj, dict):
        return {str(k): _make_json_safe(v) for k, v in obj.items()}

    if isinstance(obj, list):
        return [_make_json_safe(v) for v in obj]

    if isinstance(obj, tuple):
        return [_make_json_safe(v) for v in obj]

    if isinstance(obj, np.ndarray):
        return obj.tolist()

    if isinstance(obj, np.integer):
        return int(obj)

    if isinstance(obj, np.floating):
        if np.isfinite(obj):
            return float(obj)
        return None

    if isinstance(obj, float):
        if np.isfinite(obj):
            return obj
        return None

    return obj


