def plot_signal_and_events(
    t,
    x_ref,
    event_times_tx,
    event_values_tx,
    event_times_rx,
    event_values_rx,
    sensor_index,
    output_dir,
    timestamp,
    formats,
):
    """
    Plot reference signal and SoD event samples.
    """
    fig, ax = plt.subplots(figsize=(10.0, 5.2))

    ax.plot(
        t,
        x_ref,
        linewidth=2.0,
        label="x(t) filtered, DC removed, P2P adjusted",
    )

    ax.plot(
        event_times_tx,
        event_values_tx,
        "o",
        markersize=5,
        label="SoD collected samples",
    )

    ax.plot(
        event_times_rx,
        event_values_rx,
        "x",
        markersize=6,
        label="SoD received/dequantized samples",
    )

    ax.set_title("SoD samples | sensor {}".format(sensor_index))
    ax.set_xlabel("t")
    ax.set_ylabel("Amplitude")
    ax.grid(True, linestyle=":", linewidth=0.7)
    ax.legend(loc="best", frameon=True)

    fig.tight_layout()

    return {
        "signal_events_{}".format(fmt): path
        for fmt, path in save_figure(
            fig,
            output_dir,
            "{}_signal_events_{}".format(BASE_NAME, timestamp),
            formats,
        ).items()
    }


