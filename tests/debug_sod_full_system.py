    path = os.path.join(
        output_dir,
        "{}_metadata_{}.json".format(BASE_NAME, timestamp),
    )

    with open(path, "w", encoding="utf-8") as f:
        json.dump(_make_json_safe(metadata), f, indent=2)

    return path


