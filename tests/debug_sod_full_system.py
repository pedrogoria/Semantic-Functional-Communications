def generate_random_filtered_dc_p2p_signals(
    cfg: Dict[str, Any],
    rng: np.random.Generator,
    params,
    t: np.ndarray,
) -> Dict[str, np.ndarray]:
    """
    Generate one random filtered signal per sensor.

    Chain:
        random X
        -> filter_periodic
        -> remove DC
        -> adjust peak-to-peak
    """
    n_time = len(t)
    S = int(params.S)

    distribution = cfg["signal"].get("distribution", "uniform")
    W = float(cfg["signal"].get("W", params.W))
    Tt = float(cfg["signal"]["Tt"])
    tau = float(params.tau)
    peak_to_peak = float(cfg["signal"].get("peak_to_peak", 0.0))

    x_raw = np.zeros((n_time, S), dtype=float)
    x_filtered = np.zeros((n_time, S), dtype=float)
    x_no_dc = np.zeros((n_time, S), dtype=float)
    x_ref = np.zeros((n_time, S), dtype=float)

    dc_values = np.zeros(S, dtype=float)
    p2p_scales = np.ones(S, dtype=float)

    for s in range(S):
        x_raw[:, s] = _generate_random_signal(
            n_time=n_time,
            distribution=distribution,
            rng=rng,
        )

        x_filtered[:, s] = filter_periodic(
            x_raw[:, s],
            W=W,
            Tt=Tt,
            tau=tau,
        )

        x_no_dc[:, s], dc_values[s] = _remove_dc_one_period(
            x_filtered[:, s],
            Tt=Tt,
            tau=tau,
        )

        x_ref[:, s], p2p_scales[s] = _adjust_peak_to_peak(
            x_no_dc[:, s],
            peak_to_peak=peak_to_peak,
        )

    return {
        "x_raw": x_raw,
        "x_filtered": x_filtered,
        "x_no_dc": x_no_dc,
        "x_ref": x_ref,
        "dc_values": dc_values,
        "p2p_scales": p2p_scales,
    }


