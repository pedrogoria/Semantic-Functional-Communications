def run_debug_sod_full_system(
    config_path: Optional[str] = None,
    show_plots: bool = False,
    B_value: Optional[float] = None,
    seed: Optional[int] = None,
    sensor_index: Optional[int] = None,
) -> Dict[str, Any]:
    """
    Run one complete SoD debug simulation.

    Parameters
    ----------
    config_path : str or None
        Path to YAML config. If None, default in-memory config is used.

    show_plots : bool
        If True, show figures interactively after saving.

    B_value : float or None
        Optional override for cfg["system"]["B"].

    seed : int or None
        Optional override for cfg["debug"]["seed"].

    sensor_index : int or None
        Optional override for cfg["debug"]["sensor_index"].

    Returns
    -------
    dict
        Debug outputs and generated file paths.
    """
    cfg = load_yaml_config(config_path)
    cfg = ensure_output_section(cfg)

    if B_value is not None:
        cfg["system"]["B"] = float(B_value)

    if seed is not None:
        if "debug" not in cfg:
            cfg["debug"] = {}
        cfg["debug"]["seed"] = int(seed)

    if sensor_index is not None:
        if "debug" not in cfg:
            cfg["debug"] = {}
        cfg["debug"]["sensor_index"] = int(sensor_index)

    output_dir, timestamp = prepare_output_dir(cfg)

    print("\n[SoD FULL SYSTEM DEBUG]")
    print("[INFO] output_dir =", output_dir)
    print("[INFO] timestamp  =", timestamp)

    rng_seed = int(cfg.get("debug", {}).get("seed", 42))
    rng = np.random.default_rng(rng_seed)

    params = build_derived_system_parameters(cfg)

    tau = float(params.tau)
    Tt = float(cfg["signal"]["Tt"])
    t = np.arange(0.0, tau, Tt)

    selected_sensor = int(cfg.get("debug", {}).get("sensor_index", 0))

    if selected_sensor < 0 or selected_sensor >= params.S:
        raise ValueError(
            "debug.sensor_index must be in [0, {}].".format(params.S - 1)
        )

    # -------------------------------------------------------------------------
    # Generate random, filtered, DC-removed, P2P-adjusted signals
    # -------------------------------------------------------------------------
    sig = generate_random_filtered_dc_p2p_signals(
        cfg=cfg,
        rng=rng,
        params=params,
        t=t,
    )

    x_raw = sig["x_raw"]
    x_filtered = sig["x_filtered"]
    x_no_dc = sig["x_no_dc"]
    x_ref = sig["x_ref"]
    dc_values = sig["dc_values"]
    p2p_scales = sig["p2p_scales"]

    x_ref_tensor = x_ref[:, None, :]

    # -------------------------------------------------------------------------
    # FDMA budget diagnostics from core
    # -------------------------------------------------------------------------
    fdma_core = FDMACore(
        S=params.S,
        B_total=params.B,
        P_per_sensor=params.P,
        tau=params.tau,
        bandwidth_allocation=params.bandwidth_allocation,
        N0=params.N0,
        normalize_sensor_power=True,
        return_nonorthogonal_sum_preview=False,
    )

    capacity_per_sensor = np.asarray(fdma_core.get_capacity_per_sensor(), dtype=float)
    available_bits_per_sensor = capacity_per_sensor * float(params.tau)
    available_bits = float(available_bits_per_sensor[selected_sensor])

    # -------------------------------------------------------------------------
    # SoD probe WITHOUT quantization.
    # This step determines the number of transmitted events.
    # -------------------------------------------------------------------------
    sod_cfg = cfg.get("sod", {})

    threshold = float(sod_cfg.get("threshold", 0.1))
    transmit_event_times = bool(sod_cfg.get("transmit_event_times", True))
    reconstruction_mode = str(sod_cfg.get("reconstruction_mode", "zero_order_hold"))
    initial_event = bool(sod_cfg.get("initial_event", True))
    periodic_replicas = int(sod_cfg.get("periodic_replicas", 10))

    sod_probe = SoDAcquisitionCore(
        threshold=threshold,
        initial_event=initial_event,
        reconstruction_mode=reconstruction_mode,
        transmit_event_times=transmit_event_times,
        quantize_amplitudes=False,
        quantize_times=False,
    )

    acq_probe = sod_probe.acquire(
        x=x_ref_tensor,
        t=t,
    )

    event_count_per_sensor = np.array([
        int(acq_probe.event_count["period_0_sensor_{}".format(s)])
        for s in range(params.S)
    ], dtype=int)

    # -------------------------------------------------------------------------
    # Compute SoD bins from capacity and event count using theory.py.
    # This is the correct adaptive-budget rule.
    # -------------------------------------------------------------------------
    M_sod_per_sensor = compute_M_sod_per_sensor(
        available_bits_per_sensor=available_bits_per_sensor,
        event_count_per_sensor=event_count_per_sensor,
        transmit_event_times=transmit_event_times,
        force_power_of_two=params.quantization_force_power_of_two,
        rounding_mode=params.quantization_rounding_mode,
    )

    # -------------------------------------------------------------------------
    # SoD acquisition WITH quantization.
    # If transmit_event_times=True, both event amplitude and event time use the
    # same M_sod per sensor. This is the symmetric field allocation.
    # -------------------------------------------------------------------------
    sod = SoDAcquisitionCore(
        threshold=threshold,
        initial_event=initial_event,
        reconstruction_mode=reconstruction_mode,
        transmit_event_times=transmit_event_times,
        quantize_amplitudes=True,
        amplitude_bins=M_sod_per_sensor,
        quantize_times=transmit_event_times,
        time_bins=(M_sod_per_sensor if transmit_event_times else None),
    )

    acq = sod.acquire(
        x=x_ref_tensor,
        t=t,
    )

    rec = sod.reconstruct(
        acquisition_result=acq,
        t_eval=t,
    )

    # -------------------------------------------------------------------------
    # Select sensor outputs
    # -------------------------------------------------------------------------
    key = "period_0_sensor_{}".format(selected_sensor)

    x_ref_selected = x_ref[:, selected_sensor]
    x_hat_sod = rec.reconstructed_signal[:, 0, selected_sensor]

    event_times_tx = acq.event_times[key]
    event_values_tx = acq.event_values[key]

    event_times_rx = (
        acq.event_times_quantized[key]
        if acq.event_times_quantized is not None
        else acq.event_times[key]
    )

    event_values_rx = (
        acq.event_values_quantized[key]
        if acq.event_values_quantized is not None
        else acq.event_values[key]
    )

    event_value_indices = (
        acq.event_value_indices[key]
        if acq.event_value_indices is not None
        else np.array([])
    )

    event_time_indices = (
        acq.event_time_indices[key]
        if acq.event_time_indices is not None
        else np.array([])
    )

    # -------------------------------------------------------------------------
    # sinc_filter from core
    # -------------------------------------------------------------------------
    x_hat_sinc_tensor = sinc_filter(
        rec.reconstructed_signal,
        BW=float(cfg["signal"].get("W", params.W)),
        Tt=Tt,
        Tth=float(periodic_replicas) * tau,
        x_clones=int(2 * periodic_replicas),
    )

    x_hat_sinc = x_hat_sinc_tensor[:, 0, selected_sensor]

    # -------------------------------------------------------------------------
    # Metrics
    # -------------------------------------------------------------------------
    mse_sod = _compute_mse(x_ref_selected, x_hat_sod)
    mse_sinc = _compute_mse(x_ref_selected, x_hat_sinc)

    event_count = int(acq.event_count[key])
    payload_bits = float(acq.payload_bits[key])
    bits_per_event = acq.payload_metadata["bits_per_event"][key]
    payload_feasible = bool(payload_bits <= available_bits)

    print("[INFO] seed                     =", rng_seed)
    print("[INFO] selected_sensor          =", selected_sensor)
    print("[INFO] threshold                =", threshold)
    print("[INFO] transmit_event_times     =", transmit_event_times)
    print("[INFO] event_count              =", event_count)
    print("[INFO] event_count_per_sensor   =", event_count_per_sensor)
    print("[INFO] available_bits           = {:.8e}".format(available_bits))
    print("[INFO] M_sod_per_sensor         =", M_sod_per_sensor)
    print("[INFO] bits_per_event           =", bits_per_event)
    print("[INFO] payload_bits             = {:.8e}".format(payload_bits))
    print("[INFO] payload_feasible         =", payload_feasible)
    print("[INFO] mse_sod                  = {:.8e}".format(mse_sod))
    print("[INFO] mse_sinc                 = {:.8e}".format(mse_sinc))

    # -------------------------------------------------------------------------
    # Save figures
    # -------------------------------------------------------------------------
    formats = figure_formats(cfg)
    generated_files = {}

    if cfg["output"].get("save_plot", True):
        generated_files.update(
            plot_signal_and_events(
                t=t,
                x_ref=x_ref_selected,
                event_times_tx=event_times_tx,
                event_values_tx=event_values_tx,
                event_times_rx=event_times_rx,
                event_values_rx=event_values_rx,
                sensor_index=selected_sensor,
                output_dir=output_dir,
                timestamp=timestamp,
                formats=formats,
            )
        )

        generated_files.update(
            plot_reconstruction(
                t=t,
                x_ref=x_ref_selected,
                x_hat_sod=x_hat_sod,
                x_hat_sinc=x_hat_sinc,
                mse_sod=mse_sod,
                mse_sinc=mse_sinc,
                output_dir=output_dir,
                timestamp=timestamp,
                formats=formats,
            )
        )

        generated_files.update(
            plot_error(
                t=t,
                x_ref=x_ref_selected,
                x_hat_sod=x_hat_sod,
                x_hat_sinc=x_hat_sinc,
                output_dir=output_dir,
                timestamp=timestamp,
                formats=formats,
            )
        )

        generated_files.update(
            plot_channel_budget_panel(
                params=params,
                fdma_core=fdma_core,
                M_sod_per_sensor=M_sod_per_sensor,
                event_count_per_sensor=event_count_per_sensor,
                sensor_index=selected_sensor,
                payload_bits=payload_bits,
                available_bits=available_bits,
                bits_per_event=bits_per_event,
                transmit_event_times=transmit_event_times,
                output_dir=output_dir,
                timestamp=timestamp,
                formats=formats,
            )
        )

    # -------------------------------------------------------------------------
    # Save arrays
    # -------------------------------------------------------------------------
    if cfg["output"].get("save_arrays", True):
        arrays_path = save_npz_payload(
            output_dir=output_dir,
            timestamp=timestamp,
            t=t,
            x_raw=x_raw,
            x_filtered=x_filtered,
            x_no_dc=x_no_dc,
            x_ref=x_ref,
            x_hat_sod_all=rec.reconstructed_signal[:, 0, :],
            x_hat_sinc_all=x_hat_sinc_tensor[:, 0, :],
            x_ref_selected=x_ref_selected,
            x_hat_sod=x_hat_sod,
            x_hat_sinc=x_hat_sinc,
            event_times_tx=event_times_tx,
            event_values_tx=event_values_tx,
            event_times_rx=event_times_rx,
            event_values_rx=event_values_rx,
            event_value_indices=event_value_indices,
            event_time_indices=event_time_indices,
            dc_values=dc_values,
            p2p_scales=p2p_scales,
            event_count_per_sensor=event_count_per_sensor,
            M_sod_per_sensor=np.asarray(M_sod_per_sensor, dtype=int),
            available_bits_per_sensor=available_bits_per_sensor,
            capacity_per_sensor=capacity_per_sensor,
        )
        generated_files["arrays_npz"] = arrays_path

    # -------------------------------------------------------------------------
    # Save config
    # -------------------------------------------------------------------------
    if cfg["output"].get("save_config_copy", True):
        config_copy = save_config_copy_or_dump(
            cfg=cfg,
            config_path=config_path,
            output_dir=output_dir,
            timestamp=timestamp,
        )
        generated_files["config"] = config_copy

    # -------------------------------------------------------------------------
    # Save metadata
    # -------------------------------------------------------------------------
    metadata = {
        "created_at": datetime.datetime.utcnow().replace(microsecond=0).isoformat() + "Z",
        "project_root": str(PROJECT_ROOT),
        "config_path": str(config_path) if config_path is not None else None,
        "output_dir": output_dir,
        "git_commit": get_git_commit(),
        "signal": {
            "distribution": cfg["signal"].get("distribution", "uniform"),
            "W": float(cfg["signal"].get("W", params.W)),
            "tau": float(params.tau),
            "Tt": float(Tt),
            "peak_to_peak": float(cfg["signal"].get("peak_to_peak", 0.0)),
            "dc_values": dc_values,
            "p2p_scales": p2p_scales,
        },
        "physical_model": {
            "S": int(params.S),
            "B_total": float(params.B),
            "P": float(params.P),
            "N0": float(params.N0),
            "bandwidth_allocation": np.asarray(params.bandwidth_allocation, dtype=float),
            "B_per_sensor": fdma_core.get_bandwidth_per_sensor(),
            "SNR_per_sensor": fdma_core.get_snr_per_sensor(),
            "SNR_per_sensor_dB": fdma_core.get_snr_per_sensor_db(),
            "capacity_per_sensor": fdma_core.get_capacity_per_sensor(),
            "available_bits_per_sensor": available_bits_per_sensor,
        },
        "sod_budget_rule": {
            "rule": (
                "M_sod is computed from available_bits_per_sensor and "
                "event_count_per_sensor using compute_M_sod_per_sensor(...)."
            ),
            "transmit_event_times": bool(transmit_event_times),
            "fields_per_event": 2 if transmit_event_times else 1,
            "event_count_per_sensor": event_count_per_sensor,
            "M_sod_per_sensor": np.asarray(M_sod_per_sensor, dtype=int),
        },
        "sod": {
            "threshold": float(threshold),
            "transmit_event_times": bool(transmit_event_times),
            "reconstruction_mode": reconstruction_mode,
            "initial_event": bool(initial_event),
            "amplitude_bins": sod.amplitude_bins,
            "time_bins": sod.time_bins,
            "selected_sensor": int(selected_sensor),
            "event_count": int(event_count),
            "payload_bits": float(payload_bits),
            "available_bits": float(available_bits),
            "payload_feasible": bool(payload_feasible),
            "bits_per_event": bits_per_event,
            "amplitude_quantization_metadata": acq.amplitude_quantization_metadata,
            "time_quantization_metadata": acq.time_quantization_metadata,
            "payload_metadata": acq.payload_metadata,
        },
        "metrics": {
            "mse_sod": float(mse_sod),
            "mse_sinc": float(mse_sinc),
        },
        "generated_files": generated_files,
    }

    if cfg["output"].get("save_metadata", True):
        metadata_path = save_metadata(
            metadata=metadata,
            output_dir=output_dir,
            timestamp=timestamp,
        )
        generated_files["metadata"] = metadata_path

    print("\n[INFO] Generated files:")
    for k, v in generated_files.items():
        print("       {}: {}".format(k, v))

    if show_plots:
        plt.show(block=True)
    else:
        plt.close("all")

    return {
        "cfg": cfg,
        "params": params,
        "fdma_core": fdma_core,
        "sod_probe": sod_probe,
        "sod": sod,
        "acq_probe": acq_probe,
        "acq": acq,
        "rec": rec,
        "t": t,
        "x_raw": x_raw,
        "x_filtered": x_filtered,
        "x_no_dc": x_no_dc,
        "x_ref": x_ref,
        "x_ref_selected": x_ref_selected,
        "x_hat_sod": x_hat_sod,
        "x_hat_sinc": x_hat_sinc,
        "event_times_tx": event_times_tx,
        "event_values_tx": event_values_tx,
        "event_times_rx": event_times_rx,
        "event_values_rx": event_values_rx,
        "event_value_indices": event_value_indices,
        "event_time_indices": event_time_indices,
        "event_count": event_count,
        "event_count_per_sensor": event_count_per_sensor,
        "M_sod_per_sensor": M_sod_per_sensor,
        "payload_bits": payload_bits,
        "available_bits": available_bits,
        "available_bits_per_sensor": available_bits_per_sensor,
        "payload_feasible": payload_feasible,
        "mse_sod": mse_sod,
        "mse_sinc": mse_sinc,
        "output_dir": output_dir,
        "timestamp": timestamp,
        "generated_files": generated_files,
    }


